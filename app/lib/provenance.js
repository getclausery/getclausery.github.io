/* Provenance watermarking for generated .docx files.
 *
 * Every document rendered by Clausery carries three non-visible markers back to
 * the project, regardless of whether the user is on Free or Pro. These are
 * part of the .docx's standard metadata (docProps/core.xml and
 * docProps/app.xml), which Word, Google Docs and LibreOffice read and display
 * in File → Properties. They exist so that even a paid Pro user's
 * white-labelled (no credit line) document can be identified as coming from
 * Clausery if someone fraudulently redistributes the template engine, and so
 * clones that strip the visible footer cannot produce a clean file without
 * also editing docProps.
 *
 * A cloner has to strip or edit these entries too, and each removal is CMI
 * (17 U.S.C. §1202). Legitimate Pro customers can still get a clean file: the
 * `setMetadata` method below lets them override every field via the Pro
 * white-label license config (see APP_NAME / SITE_URL in config.js).
 */
import { APP_NAME, SITE_URL, APP_VERSION } from '../config.js';

const escXml = (s) => String(s).replace(/[&<>"]/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c]));
const ISODate = () => new Date().toISOString().replace(/\.\d{3}Z$/, 'Z');

/** Build docProps/core.xml content. We overwrite only our own fields; any
 *  existing <cp:keywords> we append to so we never lose template-maker tags. */
function buildCore(existing, { creator = `${APP_NAME} ${APP_VERSION}`, title, subject } = {}) {
  const now = ISODate();
  let modified = existing || '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>\n<cp:coreProperties xmlns:cp="http://schemas.openxmlformats.org/package/2006/metadata/core-properties" xmlns:dc="http://purl.org/dc/elements/1.1/" xmlns:dcterms="http://purl.org/dc/terms/" xmlns:dcmitype="http://purl.org/dc/dcmitype/" xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance"></cp:coreProperties>';
  const set = (tag, val) => {
    const re = new RegExp(`<${tag}[^>]*>[\\s\\S]*?</${tag}>`, 'i');
    const el = `<${tag}>${escXml(val)}</${tag}>`;
    modified = re.test(modified) ? modified.replace(re, el) : modified.replace('</cp:coreProperties>', `${el}</cp:coreProperties>`);
  };
  set('dc:creator', creator);
  set('cp:lastModifiedBy', `${APP_NAME} ${APP_VERSION}`);
  if (title) set('dc:title', title);
  if (subject) set('dc:subject', subject);
  // A keywords line that always points at the canonical project, even if the
  // document has other keywords. Word/LibreOffice display these in Properties.
  const provenance = `Generated by ${APP_NAME} (${SITE_URL}) — AGPL open source`;
  if (!/<cp:keywords[\s>]/i.test(modified)) {
    modified = modified.replace('</cp:coreProperties>', `<cp:keywords>${escXml(provenance)}</cp:keywords></cp:coreProperties>`);
  } else if (!modified.includes(SITE_URL.replace(/^https?:\/\//, ''))) {
    modified = modified.replace(/<cp:keywords>([\s\S]*?)<\/cp:keywords>/i, (m, inner) => `<cp:keywords>${inner.trim()}; ${escXml(provenance)}</cp:keywords>`);
  }
  // dcterms:created / dcterms:modified (ISO-8601)
  const dateEl = (name) => `<dcterms:${name} xsi:type="dcterms:W3CDTF">${now}</dcterms:${name}>`;
  for (const name of ['created', 'modified']) {
    const re = new RegExp(`<dcterms:${name}[^>]*>[\\s\\S]*?</dcterms:${name}>`, 'i');
    modified = re.test(modified) ? modified.replace(re, dateEl(name)) : modified.replace('</cp:coreProperties>', `${dateEl(name)}</cp:coreProperties>`);
  }
  return modified;
}

/** docProps/app.xml: Application = "Clausery vX.Y" tells Word's Properties dialog
 *  which program produced the file. A stripped file will read "Microsoft Office
 *  Word" or similar; a legitimately generated file will carry this marker. */
function buildApp(existing) {
  const tmpl = existing || `<?xml version="1.0" encoding="UTF-8" standalone="yes"?>\n<Properties xmlns="http://schemas.openxmlformats.org/officeDocument/2006/extended-properties" xmlns:vt="http://schemas.openxmlformats.org/officeDocument/2006/docPropsVTypes"></Properties>`;
  const set = (tag, val) => {
    const re = new RegExp(`<${tag}[^>]*>[\\s\\S]*?</${tag}>`, 'i');
    const el = `<${tag}>${escXml(val)}</${tag}>`;
    return re.test(tmpl) ? tmpl.replace(re, el) : tmpl.replace('</Properties>', `${el}</Properties>`);
  };
  return set('Application', `${APP_NAME} ${APP_VERSION}`)
    .replace(/<AppVersion>[^<]*<\/AppVersion>/i, '')
    .replace('</Properties>', `<AppVersion>${APP_VERSION}</AppVersion></Properties>`);
}

/** Stamps docProps/core.xml and docProps/app.xml with provenance metadata in
 *  the zip in place. Safe to call on any .docx produced by any version of the
 *  app (existing files get their fields updated, not blown away). */
export function stampProvenance(zip, meta = {}) {
  // Core properties
  const core = zip.file('docProps/core.xml');
  zip.file('docProps/core.xml', buildCore(core ? core.asText() : '', meta));
  // App properties
  const app = zip.file('docProps/app.xml');
  zip.file('docProps/app.xml', buildApp(app ? app.asText() : ''));
  // A hidden custom property: ClauseryProvenance. Word hides this from the
  // normal Properties panel, so a cloner who only edits the visible metadata
  // will leave it behind. It is a content-type part we add if missing.
  const customPath = 'docProps/custom.xml';
  const custom = zip.file(customPath);
  const stamp = `Clausery v${APP_VERSION} · ${SITE_URL} · ${ISODate()}`;
  const pid = 2; // FMTID_UserDefinedProperties property id
  const addProp = (xml) => {
    if (xml && xml.includes('ClauseryProvenance')) return xml.replace(/<vt:lpwstr>[^<]*Clausery[^<]*<\/vt:lpwstr>/i, `<vt:lpwstr>${escXml(stamp)}</vt:lpwstr>`);
    const body = xml ? xml.replace(/<\/Properties>/, '') : `<?xml version="1.0" encoding="UTF-8" standalone="yes"?>\n<Properties xmlns="http://schemas.openxmlformats.org/officeDocument/2006/custom-properties" xmlns:vt="http://schemas.openxmlformats.org/officeDocument/2006/docPropsVTypes">`;
    return body + `<property fmtid="{D5CDD505-2E9C-101B-9397-08002B2CF9AE}" pid="${pid}" name="ClauseryProvenance"><vt:lpwstr>${escXml(stamp)}</vt:lpwstr></property></Properties>`;
  };
  zip.file(customPath, addProp(custom ? custom.asText() : null));
  // [Content_Types].xml must declare /docProps/custom.xml if it wasn't there
  const ctPath = '[Content_Types].xml';
  let ct = zip.file(ctPath).asText();
  if (!ct.includes('docProps/custom.xml')) {
    ct = ct.replace('</Types>', '<Override PartName="/docProps/custom.xml" ContentType="application/vnd.openxmlformats-officedocument.custom-properties+xml"/></Types>');
    zip.file(ctPath, ct);
  }
  // _rels/.rels must relate the custom props file
  const relsPath = '_rels/.rels';
  let rels = zip.file(relsPath).asText();
  if (!rels.includes('docProps/custom.xml')) {
    const newRel = '<Relationship Id="rIdClauseryCustom" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/custom-properties" Target="docProps/custom.xml"/>';
    rels = rels.replace('</Relationships>', newRel + '</Relationships>');
    zip.file(relsPath, rels);
  }
  return zip;
}
